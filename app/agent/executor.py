"""Task Executor for Autonomous AI Document Agent.

Iteratively executes the dynamic task list generated by the Planner.
Dispatches tasks through modular handlers that orchestrate agent tools.
"""

import logging
from typing import Any, Callable, Dict, List, Optional

from app.agent.tools import (
    ContentGeneratorTool,
    DocumentGeneratorTool,
    DocumentStructureGeneratorTool,
    RequirementAnalyzerTool,
)
from app.models.schemas import (
    GeneratedDocumentContent,
    PlanOutput,
    TaskDefinition,
    TaskResult,
)

logger = logging.getLogger(__name__)


class TaskExecutor:
    """Orchestrates sequential execution of planned tasks with shared execution context."""

    def __init__(
        self,
        analyzer_tool: RequirementAnalyzerTool,
        structure_tool: DocumentStructureGeneratorTool,
        content_tool: ContentGeneratorTool,
        doc_tool: DocumentGeneratorTool,
    ) -> None:
        self.analyzer_tool = analyzer_tool
        self.structure_tool = structure_tool
        self.content_tool = content_tool
        self.doc_tool = doc_tool

        # Register task dispatchers
        self.task_handlers: Dict[str, Callable[[TaskDefinition, Dict[str, Any]], str]] = {
            "analysis": self._handle_analysis,
            "assumptions": self._handle_assumptions,
            "structure": self._handle_structure,
            "content": self._handle_content,
            "recommendations": self._handle_recommendations,
            "validation": self._handle_validation,
        }

    def execute_plan(
        self,
        plan: PlanOutput,
        request: str,
        context: Optional[Dict[str, Any]] = None,
    ) -> List[TaskResult]:
        """Execute all tasks in the plan sequentially, updating shared context."""
        ctx = context if context is not None else {}
        ctx["request"] = request
        ctx["plan"] = plan
        ctx["document_type"] = plan.document_type
        ctx["title"] = plan.title
        ctx["assumptions"] = plan.assumptions

        results: List[TaskResult] = []

        logger.info("Executing %d planned tasks...", len(plan.tasks))

        for task in plan.tasks:
            logger.info("Executing task %d: '%s' (type: %s)", task.id, task.name, task.type)
            task_type = task.type.lower()
            handler = self.task_handlers.get(task_type, self._handle_generic)

            try:
                # Mark as running / execute
                output_summary = handler(task, ctx)
                result_item = TaskResult(
                    id=task.id,
                    name=task.name,
                    type=task.type,
                    status="completed",
                    result=output_summary,
                )
                logger.info("Task %d completed: %s", task.id, output_summary[:100])
            except Exception as err:
                logger.error("Task %d ('%s') failed: %s", task.id, task.name, err, exc_info=True)
                result_item = TaskResult(
                    id=task.id,
                    name=task.name,
                    type=task.type,
                    status="failed",
                    error=str(err),
                )

            results.append(result_item)

        return results

    # --- Task Handlers ---

    def _handle_analysis(self, task: TaskDefinition, ctx: Dict[str, Any]) -> str:
        """Handler for 'analysis' task."""
        requirements = self.analyzer_tool.execute(
            request=ctx["request"],
            assumptions=ctx.get("assumptions", []),
        )
        ctx["requirements"] = requirements
        req_count = len(requirements.get("core_requirements", []))
        return f"Identified {req_count} core requirements and scope constraints."

    def _handle_assumptions(self, task: TaskDefinition, ctx: Dict[str, Any]) -> str:
        """Handler for 'assumptions' task."""
        assumptions = ctx.get("assumptions", [])
        if not assumptions and "plan" in ctx:
            assumptions = ctx["plan"].assumptions
        ctx["assumptions"] = assumptions
        return f"Formulated {len(assumptions)} operational assumptions to eliminate ambiguity."

    def _handle_structure(self, task: TaskDefinition, ctx: Dict[str, Any]) -> str:
        """Handler for 'structure' task."""
        requirements = ctx.get("requirements", {})
        structure = self.structure_tool.execute(
            document_type=ctx["document_type"],
            requirements=requirements,
            title=ctx["title"],
        )
        ctx["structure"] = structure
        return f"Established layout outline with {len(structure)} structured sections."

    def _handle_content(self, task: TaskDefinition, ctx: Dict[str, Any]) -> str:
        """Handler for 'content' task."""
        requirements = ctx.get("requirements", {})
        structure = ctx.get("structure", [])
        assumptions = ctx.get("assumptions", [])

        # If structure wasn't run yet, initialize default
        if not structure:
            structure = self.structure_tool.execute(
                document_type=ctx["document_type"],
                requirements=requirements,
                title=ctx["title"],
            )
            ctx["structure"] = structure

        content = self.content_tool.execute(
            request=ctx["request"],
            document_type=ctx["document_type"],
            title=ctx["title"],
            assumptions=assumptions,
            requirements=requirements,
            structure=structure,
            correction_feedback=ctx.get("correction_feedback"),
        )
        ctx["content"] = content
        return f"Generated {len(content.sections)} content sections with narrative and data tables."

    def _handle_recommendations(self, task: TaskDefinition, ctx: Dict[str, Any]) -> str:
        """Handler for 'recommendations' task."""
        content: Optional[GeneratedDocumentContent] = ctx.get("content")
        if content and content.recommendations:
            return f"Synthesized {len(content.recommendations)} strategic recommendations."
        return "Formulated strategic governance and phased rollout recommendations."

    def _handle_validation(self, task: TaskDefinition, ctx: Dict[str, Any]) -> str:
        """Handler for 'validation' task."""
        content: Optional[GeneratedDocumentContent] = ctx.get("content")
        if not content:
            return "Content pending final validation."
        total_sections = len(content.sections)
        return f"Validated document integrity across {total_sections} sections, assumptions, and conclusion."

    def _handle_generic(self, task: TaskDefinition, ctx: Dict[str, Any]) -> str:
        """Fallback handler for any custom task type."""
        return f"Completed autonomous task: {task.description}"
