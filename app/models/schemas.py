"""Pydantic schemas and data transfer objects for Autonomous AI Document Agent."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class AgentRequest(BaseModel):
    """Input payload for the autonomous document agent."""

    request: str = Field(
        ...,
        min_length=10,
        max_length=5000,
        description="Natural-language description of the document to create.",
        examples=[
            "Create a professional project proposal for an AI-powered customer support chatbot."
        ],
    )


class TaskDefinition(BaseModel):
    """Planner task specification representing an autonomous work step."""

    id: int = Field(..., description="Unique task identifier in sequence.")
    name: str = Field(..., description="Short descriptive name of the task.")
    type: str = Field(
        ...,
        description="Task category (e.g., 'analysis', 'structure', 'content', 'validation').",
    )
    description: str = Field(
        ..., description="Detailed description of what this task accomplishes."
    )
    status: str = Field(
        default="pending",
        description="Current task status ('pending', 'running', 'completed', 'failed').",
    )


class PlanOutput(BaseModel):
    """Structured plan dynamically generated by the LLM Planner."""

    document_type: str = Field(
        ...,
        description="Type of document (e.g., 'Project Proposal', 'Implementation Plan').",
    )
    title: str = Field(..., description="Professional document title.")
    objective: str = Field(
        ..., description="Clear objective of the document based on the user request."
    )
    assumptions: List[str] = Field(
        default_factory=list,
        description="Reasonable assumptions made to resolve any ambiguity or missing information.",
    )
    tasks: List[TaskDefinition] = Field(
        default_factory=list,
        description="Ordered list of tasks dynamically planned by the LLM.",
    )


class TaskResult(BaseModel):
    """Execution status and result for an individual plan task."""

    id: int = Field(..., description="Task ID matching the plan.")
    name: str = Field(..., description="Task name.")
    type: str = Field(..., description="Task category.")
    status: str = Field(..., description="Execution status: completed, failed, or skipped.")
    result: Optional[str] = Field(
        default=None, description="Summary or output of the task execution."
    )
    error: Optional[str] = Field(
        default=None, description="Error message if task execution failed."
    )


class ReflectionResult(BaseModel):
    """Result of the quality self-check reflection step."""

    passed: bool = Field(
        ..., description="Whether the document meets quality and completeness standards."
    )
    score: int = Field(
        ..., ge=1, le=10, description="Quality rating score on a 1-10 scale."
    )
    issues: List[str] = Field(
        default_factory=list,
        description="List of identified missing elements, gaps, or inconsistencies.",
    )
    improvements: List[str] = Field(
        default_factory=list,
        description="Concrete recommended revisions applied or proposed.",
    )


class DocumentResult(BaseModel):
    """Metadata regarding the generated Microsoft Word document."""

    title: str = Field(..., description="Title of the generated document.")
    document_type: str = Field(..., description="Category or document type.")
    filename: str = Field(..., description="Filename on the server.")
    download_url: str = Field(..., description="Relative download URL.")


class AgentResponse(BaseModel):
    """Standard API response returned by POST /agent."""

    status: str = Field(
        ...,
        description="Overall agent status: 'completed' or 'failed'.",
        examples=["completed"],
    )
    message: str = Field(
        ...,
        description="Human-readable message explaining the outcome.",
        examples=["Agent completed the request successfully."],
    )
    request: str = Field(..., description="Echo of original user request.")
    document: Optional[DocumentResult] = Field(
        default=None, description="Generated document details."
    )
    plan: List[TaskResult] = Field(
        default_factory=list, description="Ordered list of executed plan tasks."
    )
    assumptions: List[str] = Field(
        default_factory=list,
        description="Assumptions made by the agent to handle ambiguity.",
    )
    execution: List[TaskResult] = Field(
        default_factory=list,
        description="Task execution records.",
    )
    reflection: Optional[ReflectionResult] = Field(
        default=None, description="Reflection and quality evaluation outcome."
    )


class DocumentSection(BaseModel):
    """Structured representation of a document section for rich formatting."""

    heading: str = Field(..., description="Section title or heading.")
    level: int = Field(default=1, ge=1, le=3, description="Heading level: 1 or 2.")
    content: Optional[str] = Field(
        default=None, description="Paragraph narrative text."
    )
    bullets: List[str] = Field(
        default_factory=list, description="Bulleted list items."
    )
    numbered: List[str] = Field(
        default_factory=list, description="Numbered list items."
    )
    table_headers: List[str] = Field(
        default_factory=list, description="Column headers if section contains a table."
    )
    table_rows: List[List[str]] = Field(
        default_factory=list, description="Data rows if section contains a table."
    )


class GeneratedDocumentContent(BaseModel):
    """Complete content model produced before DOCX generation."""

    title: str
    document_type: str
    subtitle: Optional[str] = None
    executive_summary: Optional[str] = None
    assumptions: List[str] = Field(default_factory=list)
    sections: List[DocumentSection] = Field(default_factory=list)
    recommendations: List[str] = Field(default_factory=list)
    conclusion: Optional[str] = None
