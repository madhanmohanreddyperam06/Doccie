"""Docx Document Generator for Autonomous AI Document Agent.

Produces polished, presentation-ready Microsoft Word (.docx) documents with:
- Professional executive styling and typography
- Structured headings, sub-headings, and body paragraphs
- Executive Summary & Context Metadata
- Styled callout boxes for Assumptions
- Professionally formatted data tables with styled header rows
- Bulleted and numbered lists
- Actionable Recommendations and Strategic Conclusion
"""

from datetime import datetime
import logging
import os
from pathlib import Path
from typing import Any, Dict, List, Optional
import uuid

import docx
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement, parse_xml
from docx.oxml.ns import nsdecls, qn
from docx.shared import Inches, Pt, RGBColor

from app.models.schemas import DocumentSection, GeneratedDocumentContent

logger = logging.getLogger(__name__)

# Color Palette Constants
COLOR_PRIMARY = RGBColor(30, 58, 138)       # Deep Navy #1E3A8A
COLOR_SECONDARY = RGBColor(37, 99, 235)     # Royal Blue #2563EB
COLOR_TEXT_DARK = RGBColor(31, 41, 55)      # Charcoal #1F2937
COLOR_TEXT_MUTED = RGBColor(100, 116, 139)  # Slate Muted #64748B
HEX_PRIMARY = "1E3A8A"
HEX_BG_LIGHT = "F8FAFC"
HEX_CALLOUT_BG = "F1F5F9"
HEX_BORDER = "CBD5E1"


class DocxDocumentGenerator:
    """Generates professional Microsoft Word (.docx) files from structured content."""

    def __init__(self, output_dir: Optional[str] = None) -> None:
        self.output_dir = Path(
            output_dir or os.getenv("GENERATED_DIR", "generated")
        )
        self.output_dir.mkdir(parents=True, exist_ok=True)

    @staticmethod
    def _set_cell_background(cell, hex_color: str) -> None:
        """Set shading background color for a table cell."""
        shading = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{hex_color}"/>')
        cell._tc.get_or_add_tcPr().append(shading)

    @staticmethod
    def _set_cell_margins(cell, top=100, bottom=100, left=150, right=150) -> None:
        """Set internal padding/margins for a table cell in twentieths of a point (dxa)."""
        tcPr = cell._tc.get_or_add_tcPr()
        tcMar = OxmlElement("w:tcMar")
        for side, val in [("top", top), ("bottom", bottom), ("left", left), ("right", right)]:
            node = OxmlElement(f"w:{side}")
            node.set(qn("w:w"), str(val))
            node.set(qn("w:type"), "dxa")
            tcMar.append(node)
        tcPr.append(tcMar)

    def generate(
        self,
        content: GeneratedDocumentContent,
        filename_prefix: str = "agent_document",
    ) -> Path:
        """Create a polished DOCX file from structured GeneratedDocumentContent.

        Returns:
            Path to the saved .docx file.
        """
        doc = docx.Document()

        # Set page margins to standard 1 inch
        for section in doc.sections:
            section.top_margin = Inches(1.0)
            section.bottom_margin = Inches(1.0)
            section.left_margin = Inches(1.0)
            section.right_margin = Inches(1.0)
            section.header_distance = Inches(0.5)
            section.footer_distance = Inches(0.5)

            # Footer
            footer_para = section.footer.paragraphs[0]
            footer_para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            footer_run = footer_para.add_run(
                f"{content.title}  |  Generated by Autonomous AI Agent"
            )
            footer_run.font.size = Pt(8.5)
            footer_run.font.color.rgb = COLOR_TEXT_MUTED

        # 1. Document Title
        title_p = doc.add_paragraph()
        title_p.paragraph_format.space_before = Pt(0)
        title_p.paragraph_format.space_after = Pt(4)
        title_run = title_p.add_run(content.title)
        title_run.font.name = "Calibri"
        title_run.font.size = Pt(24)
        title_run.font.bold = True
        title_run.font.color.rgb = COLOR_PRIMARY

        # 2. Subtitle / Document Type & Date
        subtitle_p = doc.add_paragraph()
        subtitle_p.paragraph_format.space_before = Pt(0)
        subtitle_p.paragraph_format.space_after = Pt(16)

        sub_text = content.subtitle or content.document_type
        sub_run = subtitle_p.add_run(sub_text)
        sub_run.font.name = "Calibri"
        sub_run.font.size = Pt(12)
        sub_run.font.color.rgb = COLOR_SECONDARY
        sub_run.font.italic = True

        date_str = datetime.now().strftime("%B %d, %Y")
        meta_run = subtitle_p.add_run(f"  •  Published: {date_str}  •  Status: Autonomous Draft")
        meta_run.font.name = "Calibri"
        meta_run.font.size = Pt(9.5)
        meta_run.font.color.rgb = COLOR_TEXT_MUTED

        # Horizontal accent rule
        doc.add_paragraph().paragraph_format.space_after = Pt(8)

        # 3. Executive Summary
        if content.executive_summary:
            h1 = self._add_heading_1(doc, "Executive Summary")
            p = doc.add_paragraph()
            p.paragraph_format.line_spacing = 1.15
            p.paragraph_format.space_after = Pt(12)
            run = p.add_run(content.executive_summary)
            run.font.name = "Calibri"
            run.font.size = Pt(11)
            run.font.color.rgb = COLOR_TEXT_DARK

        # 4. Strategic Assumptions Callout Box
        if content.assumptions:
            self._add_heading_1(doc, "Key Planning Assumptions")
            callout_table = doc.add_table(rows=1, cols=1)
            callout_table.alignment = WD_TABLE_ALIGNMENT.CENTER
            callout_table.autofit = False

            cell = callout_table.cell(0, 0)
            cell.width = Inches(6.5)
            self._set_cell_background(cell, HEX_CALLOUT_BG)
            self._set_cell_margins(cell, top=140, bottom=140, left=200, right=200)

            # Inside callout
            intro_p = cell.paragraphs[0]
            intro_p.paragraph_format.space_after = Pt(4)
            intro_run = intro_p.add_run(
                "The autonomous agent formulated the following operational assumptions to establish project boundaries and eliminate ambiguity:"
            )
            intro_run.font.name = "Calibri"
            intro_run.font.size = Pt(10)
            intro_run.font.italic = True
            intro_run.font.color.rgb = COLOR_TEXT_MUTED

            for assumption in content.assumptions:
                bp = cell.add_paragraph()
                bp.paragraph_format.space_after = Pt(3)
                bp.paragraph_format.left_indent = Inches(0.2)
                brun = bp.add_run(f"•  {assumption}")
                brun.font.name = "Calibri"
                brun.font.size = Pt(10)
                brun.font.color.rgb = COLOR_TEXT_DARK

            doc.add_paragraph().paragraph_format.space_after = Pt(12)

        # 5. Core Content Sections
        for section in content.sections:
            if section.level == 1:
                self._add_heading_1(doc, section.heading)
            else:
                self._add_heading_2(doc, section.heading)

            if section.content:
                p = doc.add_paragraph()
                p.paragraph_format.line_spacing = 1.15
                p.paragraph_format.space_after = Pt(8)
                run = p.add_run(section.content)
                run.font.name = "Calibri"
                run.font.size = Pt(11)
                run.font.color.rgb = COLOR_TEXT_DARK

            # Bullets
            for bullet in section.bullets:
                bp = doc.add_paragraph(style="List Bullet")
                bp.paragraph_format.space_after = Pt(3)
                brun = bp.add_run(bullet)
                brun.font.name = "Calibri"
                brun.font.size = Pt(10.5)
                brun.font.color.rgb = COLOR_TEXT_DARK

            # Numbered list
            for num_item in section.numbered:
                np = doc.add_paragraph(style="List Number")
                np.paragraph_format.space_after = Pt(3)
                nrun = np.add_run(num_item)
                nrun.font.name = "Calibri"
                nrun.font.size = Pt(10.5)
                nrun.font.color.rgb = COLOR_TEXT_DARK

            # Table (if present)
            if section.table_headers and section.table_rows:
                self._add_styled_table(doc, section.table_headers, section.table_rows)

        # 6. Strategic Recommendations
        if content.recommendations:
            self._add_heading_1(doc, "Strategic Recommendations")
            for rec in content.recommendations:
                rp = doc.add_paragraph(style="List Bullet")
                rp.paragraph_format.space_after = Pt(4)
                rrun = rp.add_run(rec)
                rrun.font.name = "Calibri"
                rrun.font.size = Pt(10.5)
                rrun.font.color.rgb = COLOR_TEXT_DARK

        # 7. Conclusion
        if content.conclusion:
            self._add_heading_1(doc, "Conclusion & Next Steps")
            cp = doc.add_paragraph()
            cp.paragraph_format.line_spacing = 1.15
            cp.paragraph_format.space_after = Pt(12)
            crun = cp.add_run(content.conclusion)
            crun.font.name = "Calibri"
            crun.font.size = Pt(11)
            crun.font.color.rgb = COLOR_TEXT_DARK

        # Generate unique safe filename
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        rand_suffix = uuid.uuid4().hex[:4]
        filename = f"{filename_prefix}_{timestamp}_{rand_suffix}.docx"
        file_path = self.output_dir / filename

        doc.save(str(file_path))
        logger.info("Successfully generated Word document: %s", file_path)
        return file_path

    def _add_heading_1(self, doc: docx.Document, text: str):
        """Add styled Heading 1."""
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(16)
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.keep_with_next = True
        run = p.add_run(text)
        run.font.name = "Calibri"
        run.font.size = Pt(15)
        run.font.bold = True
        run.font.color.rgb = COLOR_PRIMARY
        return p

    def _add_heading_2(self, doc: docx.Document, text: str):
        """Add styled Heading 2."""
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(12)
        p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.keep_with_next = True
        run = p.add_run(text)
        run.font.name = "Calibri"
        run.font.size = Pt(12.5)
        run.font.bold = True
        run.font.color.rgb = COLOR_SECONDARY
        return p

    def _add_styled_table(
        self,
        doc: docx.Document,
        headers: List[str],
        rows: List[List[str]],
    ) -> None:
        """Add a beautifully styled table with Navy header and zebra striping."""
        num_cols = len(headers)
        if num_cols == 0:
            return

        table = doc.add_table(rows=len(rows) + 1, cols=num_cols)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.autofit = True

        # Header Row
        header_row = table.rows[0]
        for col_idx, heading_text in enumerate(headers):
            cell = header_row.cells[col_idx]
            self._set_cell_background(cell, HEX_PRIMARY)
            self._set_cell_margins(cell, top=120, bottom=120, left=140, right=140)
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            run = p.add_run(str(heading_text))
            run.font.name = "Calibri"
            run.font.size = Pt(10)
            run.font.bold = True
            run.font.color.rgb = RGBColor(255, 255, 255)

        # Data Rows
        for r_idx, row_data in enumerate(rows):
            row = table.rows[r_idx + 1]
            bg_color = HEX_BG_LIGHT if r_idx % 2 == 1 else "FFFFFF"

            for c_idx in range(num_cols):
                cell = row.cells[c_idx]
                cell_value = str(row_data[c_idx]) if c_idx < len(row_data) else ""
                self._set_cell_background(cell, bg_color)
                self._set_cell_margins(cell, top=90, bottom=90, left=140, right=140)
                p = cell.paragraphs[0]
                p.paragraph_format.space_after = Pt(0)
                run = p.add_run(cell_value)
                run.font.name = "Calibri"
                run.font.size = Pt(9.5)
                run.font.color.rgb = COLOR_TEXT_DARK

        doc.add_paragraph().paragraph_format.space_after = Pt(10)
